import { execSync } from "child_process";
import { NextRequest, NextResponse } from "next/server";
import path from "path";
import fs from "fs";

const { create: createYoutubeDl } = require("youtube-dl-exec");

// 1. Resolve binary name dynamically
const binaryName = process.platform === "win32" ? "yt-dlp.exe" : "yt-dlp_linux";
const absoluteBinaryPath = path.join(process.cwd(), "bin", binaryName);

// 2. Chmod binary on Linux/Vercel
if (process.platform !== "win32" && fs.existsSync(absoluteBinaryPath)) {
  try {
    execSync(`chmod +x "${absoluteBinaryPath}"`);
  } catch (err) {
    console.warn("Could not set chmod execution permission on binary:", err);
  }
}

const youtubedl = createYoutubeDl(absoluteBinaryPath);

interface RequestBody {
  url: string;
  fetchContent?: boolean;
}

interface SubtitleFormat {
  ext: string;
  url: string;
  name?: string;
}

interface ProcessedSubtitleTrack {
  languageCode: string;
  languageName?: string;
  vttUrl?: string;
  allFormats: SubtitleFormat[];
}

interface ProcessedSubtitlesResponse {
  videoId: string;
  title: string;
  duration: number;
  subtitles: {
    manual: ProcessedSubtitleTrack[];
    autoGenerated: ProcessedSubtitleTrack[];
  };
}

function processSubtitleDict(
  subDict: Record<string, SubtitleFormat[]> = {},
): ProcessedSubtitleTrack[] {
  return Object.entries(subDict).map(([langCode, formats]) => {
    const vttFormat = formats.find((f) => f.ext === "vtt");

    return {
      languageCode: langCode,
      languageName: formats[0]?.name || langCode,
      vttUrl: vttFormat?.url || formats[0]?.url,
      allFormats: formats.map((f) => ({
        ext: f.ext,
        url: f.url,
      })),
    };
  });
}

export async function POST(request: NextRequest): Promise<NextResponse> {
  try {
    const body = (await request.json()) as RequestBody;
    const { url } = body;

    if (!url) {
      return NextResponse.json({ error: "URL is required" }, { status: 400 });
    }

    // 3. COPY COOKIES TO /tmp TO PREVENT READ-ONLY OS ERRORS
    const sourceCookiePath = path.join(process.cwd(), "lib", "cookies.txt");
    const writableCookiePath = path.join("/tmp", "cookies.txt");

    if (fs.existsSync(sourceCookiePath)) {
      fs.copyFileSync(sourceCookiePath, writableCookiePath);
    } else if (process.env.YOUTUBE_COOKIES_TXT) {
      fs.writeFileSync(writableCookiePath, process.env.YOUTUBE_COOKIES_TXT);
    }

    // 4. Configure yt-dlp with the writable cookie path
    const options: Record<string, any> = {
      dumpSingleJson: true,
      skipDownload: true,
      ignoreNoFormatsError: true,

      writeSubs: true,
      writeAutoSubs: true,
      subLangs: "all",

      noWarnings: true,
      noCheckCertificates: true,
      cookies: writableCookiePath,
      extractorArgs: "youtube:player_client=android,ios,mweb,web_creator,tv",
    };

    const info = await youtubedl(url, options);

    const responseData: ProcessedSubtitlesResponse = {
      videoId: info.id,
      title: info.title,
      duration: info.duration || 0,
      subtitles: {
        manual: processSubtitleDict(info.subtitles),
        autoGenerated: processSubtitleDict(info.automatic_captions),
      },
    };

    return NextResponse.json(responseData);
  } catch (error) {
    console.error("Subtitle Extraction Error:", error);
    const errorMessage =
      error instanceof Error ? error.message : "Unknown error";

    return NextResponse.json(
      { error: "Failed to extract subtitles", details: errorMessage },
      { status: 500 },
    );
  }
}
