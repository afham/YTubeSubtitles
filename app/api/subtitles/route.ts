// app/api/subtitles/route.ts

import { NextRequest, NextResponse } from "next/server";

interface SubtitleFormat {
  ext: string;
  url: string;
}

interface ProcessedSubtitleTrack {
  languageCode: string;
  languageName?: string;
  vttUrl?: string;
  allFormats: SubtitleFormat[];
}

const SUPPORTED_FORMATS = ["srt", "vtt", "txt", "json"];

function buildFormatsList(langCode: string, videoId: string): SubtitleFormat[] {
  return SUPPORTED_FORMATS.map((ext) => ({
    ext,
    url: `/api/subtitles/download?videoId=${videoId}&langCode=${langCode}&ext=${ext}`,
  }));
}

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { videoId } = body;

    if (!videoId) {
      return NextResponse.json(
        { error: "Video ID is required" },
        { status: 400 },
      );
    }

    // Fetch YouTube page HTML to parse captions playerResponse metadata
    const response = await fetch(`https://www.youtube.com/watch?v=${videoId}`, {
      headers: {
        "User-Agent":
          "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Accept-Language": "en-US,en;q=0.9",
      },
    });

    if (!response.ok) {
      return NextResponse.json(
        { error: "Failed to fetch YouTube page content" },
        { status: 500 },
      );
    }

    const html = await response.text();

    // Extract ytInitialPlayerResponse payload from HTML
    const playerResponseMatch = html.match(
      /ytInitialPlayerResponse\s*=\s*({.+?});/,
    );

    let title = "YouTube Video";
    let duration = 0;
    let captionTracks: any[] = [];

    if (playerResponseMatch) {
      try {
        const playerResponse = JSON.parse(playerResponseMatch[1]);
        const videoDetails = playerResponse?.videoDetails;

        if (videoDetails) {
          title = videoDetails.title || title;
          duration = parseInt(videoDetails.lengthSeconds || "0", 10);
        }

        captionTracks =
          playerResponse?.captions?.playerCaptionsTracklistRenderer
            ?.captionTracks || [];
      } catch (e) {
        console.error("Error parsing ytInitialPlayerResponse:", e);
      }
    }

    const manualTracks: ProcessedSubtitleTrack[] = [];
    const autoTracks: ProcessedSubtitleTrack[] = [];

    for (const track of captionTracks) {
      const languageCode = track.languageCode;
      const languageName =
        track.name?.simpleText || track.name?.runs?.[0]?.text || languageCode;
      const isAuto =
        track.kind === "asr" || track.vssId?.startsWith("a.") || false;

      const processedTrack: ProcessedSubtitleTrack = {
        languageCode,
        languageName,
        vttUrl: track.baseUrl,
        allFormats: buildFormatsList(languageCode, videoId),
      };

      if (isAuto) {
        autoTracks.push(processedTrack);
      } else {
        manualTracks.push(processedTrack);
      }
    }

    // Fallback: If no captions were extracted from page HTML, supply English auto track
    if (manualTracks.length === 0 && autoTracks.length === 0) {
      autoTracks.push({
        languageCode: "en",
        languageName: "English (Auto-generated)",
        allFormats: buildFormatsList("en", videoId),
      });
    }

    return NextResponse.json({
      videoId,
      title,
      duration,
      subtitles: {
        manual: manualTracks,
        autoGenerated: autoTracks,
      },
    });
  } catch (error: any) {
    console.error("Error in /api/subtitles:", error);
    return NextResponse.json(
      { error: error.message || "Failed to process subtitles request" },
      { status: 500 },
    );
  }
}
